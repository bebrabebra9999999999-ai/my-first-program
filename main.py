import random

# Компьютер загадывает случайное число от 1 до 10
secret_number = random.randint(1, 10)
print("🤖 Я загадал число от 1 до 10. Попробуй угадать!")

# Цикл будет работать до тех пор, пока игрок не угадает
while True:
    # Просим пользователя ввести число
    user_guess = int(input("Введите ваше число: "))
    
    # Проверяем условия
    if user_guess < secret_number:
        print("📉 Мало! Попробуй число побольше.")
    elif user_guess > secret_number:
        print("📈 Много! Попробуй число поменьше.")
    else:
        print("🎉 Ура! Ты угадал число!")
        break # Останавливаем цикл, игра окончена
